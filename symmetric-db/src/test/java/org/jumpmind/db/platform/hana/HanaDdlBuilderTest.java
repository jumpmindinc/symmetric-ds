package org.jumpmind.db.platform.hana;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.sql.Types;

import org.jumpmind.db.model.Column;
import org.jumpmind.db.model.Table;
import org.jumpmind.db.platform.DatabaseInfo;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

class HanaDdlBuilderTest {
    private HanaDdlBuilder ddlBuilder;

    @BeforeEach
    void setUp() {
        ddlBuilder = new HanaDdlBuilder();
    }

    @Test
    void testConstructor() {
        assertNotNull(ddlBuilder);
        DatabaseInfo hanaDatabaseInfo = ddlBuilder.getDatabaseInfo();
        assertTrue(hanaDatabaseInfo.isGeneratedColumnsSupported());
        assertTrue(hanaDatabaseInfo.isSystemIndicesReturned());
        assertTrue(hanaDatabaseInfo.isAutoIncrementUpdateAllowed());
        assertEquals("NVARCHAR", hanaDatabaseInfo.getNativeType(Types.VARCHAR));
        assertEquals("NCHAR", hanaDatabaseInfo.getNativeType(Types.CHAR));
        assertEquals("BLOB", hanaDatabaseInfo.getNativeType(Types.LONGVARBINARY));
        assertEquals("NCLOB", hanaDatabaseInfo.getNativeType(Types.LONGVARCHAR));
        assertEquals("NCLOB", hanaDatabaseInfo.getNativeType(Types.CLOB));
    }

    @Test
    void testBitMapsToTinyint() {
        DatabaseInfo hanaDatabaseInfo = ddlBuilder.getDatabaseInfo();
        assertEquals("TINYINT", hanaDatabaseInfo.getNativeType(Types.BIT));
        assertEquals(Types.TINYINT, hanaDatabaseInfo.getTargetJdbcType(Types.BIT));
    }

    @Test
    void testCreateTableWithBitColumnUsesTinyint() {
        Table table = new Table("test_bit");
        Column id = new Column("id", true, Types.INTEGER, 0, 0);
        id.setRequired(true);
        table.addColumn(id);
        table.addColumn(new Column("flag", false, Types.BIT, 0, 0));
        String ddl = ddlBuilder.createTable(table);
        assertTrue(ddl.contains("\"flag\" TINYINT"), ddl);
        assertFalse(ddl.contains("BIT"), ddl);
    }

    @Test
    void testWriteColumnAutoIncrementStmt() {
        StringBuilder ddl = new StringBuilder();
        ddlBuilder.writeColumnAutoIncrementStmt(null, null, ddl);
        assertEquals(" GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) ", ddl.toString());
    }

    @Test
    void testNewidDefaultIsOmitted() {
        String ddl = ddlBuilder.createTable(tableWithUidDefault("newid()"));
        assertTrue(ddl.contains("\"c_uid\" NCHAR(36)"), ddl);
        assertFalse(ddl.toUpperCase().contains("NEWID"), ddl);
    }

    @Test
    void testParenthesizedNewsequentialidDefaultIsOmitted() {
        String ddl = ddlBuilder.createTable(tableWithUidDefault("(NewSequentialId())"));
        assertFalse(ddl.toUpperCase().contains("NEWSEQUENTIALID"), ddl);
        assertFalse(ddl.contains("DEFAULT"), ddl);
    }

    @Test
    void testCurrentTimestampDefaultIsKept() {
        Column id = new Column("id", true, Types.INTEGER, 10, 0);
        Column created = new Column("created", false, Types.TIMESTAMP, 0, 0);
        created.setDefaultValue("CURRENT_TIMESTAMP");
        String ddl = ddlBuilder.createTable(new Table("t_default", id, created));
        assertTrue(ddl.contains("DEFAULT CURRENT_TIMESTAMP"), ddl);
    }

    @Test
    void testIsUnsupportedDefaultFunction() {
        assertTrue(ddlBuilder.isUnsupportedDefaultFunction(" NEWID() "));
        assertTrue(ddlBuilder.isUnsupportedDefaultFunction("((newsequentialid()))"));
        assertFalse(ddlBuilder.isUnsupportedDefaultFunction("CURRENT_TIMESTAMP"));
        assertFalse(ddlBuilder.isUnsupportedDefaultFunction("'newid()'"));
        assertFalse(ddlBuilder.isUnsupportedDefaultFunction(null));
    }

    private static Table tableWithUidDefault(String defaultValue) {
        Column id = new Column("id", true, Types.INTEGER, 10, 0);
        Column uid = new Column("c_uid", false, Types.CHAR, 36, 0);
        uid.setDefaultValue(defaultValue);
        return new Table("t_uid", id, uid);
    }
}
